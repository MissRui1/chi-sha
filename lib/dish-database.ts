export const normalizeFoodName = (value: string) =>
  value.replace(/\s+/g, "").toLowerCase();

export const isKnownFoodName = (
  value: string,
  pool = curatedDishNames
) => {
  const normalized = normalizeFoodName(value);
  return pool.some((item) => normalizeFoodName(item) === normalized);
};
