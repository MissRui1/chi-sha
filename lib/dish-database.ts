const normalizeRegion = (value: string) =>
  value
    .replace(/特别行政区|壮族自治区|回族自治区|维吾尔自治区|自治区|省|市|地区|盟|自治州/g, "")
    .trim();

export const getRegionalDishNames = (
  location?: {
    province?: string;
    city?: string;
    district?: string;
  }
) => {
  const regions = [
    location?.city,
    location?.province,
    location?.district,
  ]
    .map((item) => normalizeRegion(item ?? ""))
    .filter(Boolean);

  const dishes = regions.flatMap((region) =>
    Object.entries(regionalDishAliases)
      .filter(([alias]) => region.includes(alias) || alias.includes(region))
      .flatMap(([, names]) => names)
  );

  return [...new Set(dishes)].filter((dish) =>
    curatedDishNames.includes(dish)
  );
};

